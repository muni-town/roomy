-- Roomy global SQLite schema (data/global.sqlite).
--
-- Cross-space data only:
--   - the `joinedSpace` / `leftSpace` membership edges (head = user DID,
--     tail = space DID). All other edge labels (member, admin, author, link,
--     reply, forward, ...) live in the per-space DBs.
--   - the global `profiles` table: the authoritative per-user Roomy profile
--     (one row per DID). The atproto collection lexicon defines a single
--     global Roomy profile per user, so profiles are NOT per-space — they
--     live here. Per-space DBs keep a denormalised copy (comp_user /
--     comp_info) for stream-scoped profiles; cross-stream authors/members
--     resolve from this table at read time (queries/profileStore.ts).
--
-- The global DB is derived data: it can be regenerated by replaying the local
-- event log. Deleting it is safe: it is rebuilt from those sources.

pragma foreign_keys = on;

create table if not exists global_schema_version (
  id integer primary key check (id = 1),
  version text not null
) strict;

-- Tracks asynchronous/data post-migrations separately from structural DDL.
-- Only versions declared `kind: "data"` in GLOBAL_MIGRATIONS
-- (globalVersions.ts) get a row here (the worker inserts it at upgrade time);
-- startup runs the registered task and stamps completion only after the whole
-- task succeeds, so interrupted deployments retry safely. Structural versions
-- never appear here.
create table if not exists global_schema_migrations (
  version text primary key,
  completed_at integer
) strict;

create table if not exists edges (
  head text not null, -- user did
  tail text not null, -- space did
  label text not null, -- 'joinedSpace' | 'leftSpace'
  payload text,
  created_at integer not null default (unixepoch() * 1000),
  updated_at integer not null default (unixepoch() * 1000),
  primary key (head, tail, label)
) strict;
create index if not exists idx_edges_label on edges(label);
create index if not exists idx_edges_label_head on edges(label, head);
create index if not exists idx_edges_label_tail on edges(label, tail);

-- Global per-user Roomy profile (authoritative). One row per DID. Populated
-- by the profile fetch path (insertProfiles / insertProfilesWithExtras) and
-- by the SetUserProfile materialiser. `getProfile` reads from here.
create table if not exists profiles (
  did text primary key,
  handle text,
  name text,
  avatar text,
  description text,
  banner text,
  pronouns text,
  website text,
  updated_at integer not null default (unixepoch() * 1000)
) strict;
create index if not exists idx_profiles_handle on profiles(handle);

-- Global entity → space index. Maps every materialised entity id (room,
-- message, ...) to the space DID that owns it. Populated during
-- materialization: when an `insert into entities` statement is
-- applied to a per-space DB, the same (entity_id, space_did) pair is
-- recorded here. Used by `openSpaceDbForEntity` to resolve which per-space
-- DB a room/message id lives in.
create table if not exists entity_space (
  entity_id text primary key,
  space_did text not null
) strict;
create index if not exists idx_entity_space_space on entity_space(space_did);

-- Global pending-embed-links index. Dual-written during
-- materialization alongside the per-space `comp_embed_link` rows so the
-- centralized embed sweeper can find pending work with a single query across
-- ALL per-space DBs, instead of iterating every space DB. Each row records
-- the space DID and message id that contained the URL so the sweeper can
-- route enrichment + invalidation to the correct per-space DB and delete the
-- row once processed.
create table if not exists pending_links (
  space_did text not null,
  message_id text not null,
  url text not null,
  created_at integer not null default (unixepoch() * 1000),
  primary key (space_did, message_id, url)
) strict;
create index if not exists idx_pending_links_created on pending_links(created_at);

-- Enriched link metadata, fetched from the external embed service. Keyed by
-- the URL itself, so it is the same row for every space that shared the link
-- and is written ONCE rather than per space.
--
-- The value is a function of an outbound HTTP response, not of the event log,
-- so it does not belong in a per-space projection: a space rebuilt from the
-- log (or derived on a second worker) would render bare links until its own
-- sweeper happened to re-fetch them. The read paths join against this table in
-- JS, after collecting the URLs their page holds.
--
-- `embed_json` is null when the service had no data. `retry_after` is a
-- millisecond epoch: when set (and in the past) the row is a TRANSIENT failure
-- (timeout / 5xx / network) eligible for re-enrichment; null means no retry is
-- needed (success, or a definitive failure such as a 404). `attempts` counts
-- consecutive transient failures for backoff escalation.
--
-- `tile_version` is the tile resolver version that last finished an attempt for
-- this URL, or null/0 when none has. A reader compares it against the running
-- resolver's version to tell "this URL's tile is done" from "this URL's tile is
-- owed", which is what lets a row enriched before tiles existed be resolved on
-- its next read instead of by a backfill. The tile itself is not a column: it
-- is a field of the same `embed_json` payload (`EmbedV1.tile`), because it is a
-- property of the URL just as the OpenGraph metadata is.
create table if not exists link_embeds (
  url text primary key,
  embed_json text, -- JSON-serialized EmbedV1; null when no data
  attempts integer not null default 0, -- consecutive transient-failure count
  retry_after integer, -- epoch ms; transient failures retry after this backoff, else null
  tile_version integer, -- tile resolver version last completed; null/0 = never attempted
  fetched_at integer not null default (unixepoch() * 1000),
  created_at integer not null default (unixepoch() * 1000),
  updated_at integer not null default (unixepoch() * 1000)
) strict;
create index if not exists idx_link_embeds_retry_after on link_embeds(retry_after);

-- Global mentions index. One row per (mentioned DID, message). Dual-written
-- during materialization so a client subscribed to the `mentions:<did>` sync
-- topic can backfill history via `space.roomy.mention.getMentions` with a
-- single cross-space query, and so deleteMessage can resolve which DIDs a
-- deleted message mentioned. The DID is the stable ID (never the handle or
-- display name).
create table if not exists mentions (
  did text not null,          -- mentioned user DID
  message_id text not null,  -- the message that mentioned them
  space_did text not null,
  room_id text not null,
  kind text not null default 'mention' check(kind in ('mention','reply')),
  created_at integer not null default (unixepoch() * 1000),
  primary key (did, message_id)
) strict;
create index if not exists idx_mentions_did_created on mentions(did, created_at desc);

-- The `mentions` rows of ONE message, keyed by `message_id` alone: the edit and
-- delete paths clear a message's rows that way, and the delete reads the DIDs it
-- is removing from the same statement. The primary key is `(did, message_id)`,
-- so `message_id` is usable as a seek key only once `did` is constrained; this
-- index is what lets a `message_id`-only predicate seek instead of scanning.
create index if not exists idx_mentions_message on mentions(message_id);

-- Search backfill cursor. One row per
-- space, tracking how far the Qdrant backfill sweeper has walked that
-- space's messages (the cursor is the last message id, ULID-ordered, from
-- the space's per-space DB). Lives in the global DB because it is
-- cross-space state; a fresh/wipe-recreated Qdrant collection clears every
-- cursor so the full corpus is re-indexed. Additive DDL only — created
-- idempotently on any schema version.
create table if not exists search_backfill_cursor (
  space_did text primary key,
  cursor text not null,
  updated_at integer not null default (unixepoch() * 1000)
) strict;

-- Search backfill candidate list. One row per space the Qdrant backfill
-- sweeper considers, registered by the first insert into `entity_space` for
-- that space. The sweeper's idle heartbeat asks "which space's cursor is
-- oldest?" once a minute forever, and answering that from `entity_space`
-- meant `select distinct space_did` over the whole index on every cycle —
-- a cost proportional to the entity count that buys nothing once the corpus
-- is caught up. The candidate list plus `search_backfill_cursor` answer it
-- from two small tables.
--
-- Derived data: the next entity materialised for a space re-registers it.
create table if not exists search_backfill_space (
  space_did text primary key
) strict;

-- Register a space with the backfill sweeper as it enters the entity→space
-- index. A trigger rather than a second statement at every `entity_space`
-- write site: the index is written by materialisation, by the boot per-space
-- backfill and by test seeds, and the candidate list has to stay complete
-- for all of them.
create trigger if not exists entity_space_search_backfill
after insert on entity_space
begin
  insert or ignore into search_backfill_space (space_did) values (new.space_did);
end;

-- Channel-federation registry. Cross-space by nature, so it lives in the
-- global DB. `space_id` is the origin space (A) whose channels are exposed;
-- `federating_space_did` is the receiving space (B). One row per (A, B).
--
-- Status transitions:
--   request   -> pending
--   respond   -> active | rejected
--   remove    -> removed   (pending/active/rejected -> removed)
--   re-request after removed -> pending
--
-- Written by the SDK federation materialisers (space.roomy.federation.*),
-- routed here by statementRouting.ts (matches `space_federations`).
create table if not exists space_federations (
  space_id text not null,            -- origin space A
  federating_space_did text not null, -- receiving space B
  status text not null check(status in ('pending','active','rejected','removed')),
  requested_by_did text not null,    -- admin of B who asked
  requested_at integer not null default (unixepoch() * 1000),
  message text,                      -- request note (A-admin visible)
  decided_by_did text,               -- admin of A who decided
  decided_at integer,
  decision_message text,             -- decision note
  primary key (space_id, federating_space_did)
) strict;
create index if not exists idx_space_fed_recv on space_federations(federating_space_did, status);
create index if not exists idx_space_fed_origin_status on space_federations(space_id, status);

-- Origin grant: A-admin-set access for a receiving space B on a channel of A.
-- Mirrors role_rooms. permission null == removed / not exposed. Grants are
-- channel-scoped: threads inherit from their parent channel (see plan §5.5),
-- so lookups for a thread use its parent channel id as the room_id.
create table if not exists federation_room_permissions (
  space_id             text not null,   -- origin space A
  federating_space_did text not null,   -- receiving space B
  room_id              text not null,   -- channel id in A
  permission           text not null check(permission in ('read','readwrite')),
  primary key (space_id, federating_space_did, room_id)
) strict;
create index if not exists idx_frp_recv on federation_room_permissions(federating_space_did, permission);
create index if not exists idx_frp_room on federation_room_permissions(room_id);

-- Receiver grant: B-admin-set access for a B member, role, or ALL B members
-- on a federated channel of A. Ceiling is the origin grant
-- (federation_room_permissions).
-- kind = 'members' (grantee = B space DID, applies to every B member)
--      | 'user'    (grantee is a B user DID)
--      | 'role'    (grantee is a B role id).
create table if not exists federation_receiver_permissions (
  space_id             text not null,   -- origin space A
  federating_space_did text not null,   -- receiving space B
  room_id              text not null,   -- channel id in A
  grantee              text not null,   -- B space DID / B user DID / B role id
  kind                 text not null check(kind in ('members','user','role')),
  permission           text not null check(permission in ('read','readwrite')),
  primary key (space_id, federating_space_did, room_id, grantee, kind)
) strict;
create index if not exists idx_frper_room on federation_receiver_permissions(room_id);

-- Cross-space per-space aggregate for the admin dashboard's space list
-- (space.roomy.admin.listSpaces). One row per space that is known to have
-- member/admin edges; a MISSING row means "member_count = 0" and carries no
-- other information (the handler still reads `comp_info.name` from the space's
-- own DB for the page it returns).
--
-- Why this exists: the dashboard's default sort is member count, which only
-- lives in each space's per-space DB (`edges where head = space and label in
-- ('member','admin')`). Producing it by opening every space DB turned a single
-- dashboard request into O(all spaces) DB opens — ~19 s and ~4200 worker
-- round-trips on a 4276-space dataset, regardless of `limit`, because the
-- ordering+limit were applied only AFTER the fan-out. This table lets the
-- ordering and the cursor predicate run in SQL over one small table, so only
-- the returned page's space DBs are opened.
--
-- Written by:
--   - the boot per-space sweep (reMaterialize runs it after the entity_space
--     backfill, so an existing dataset self-heals), and
--   - `applyBatch` whenever a materialised event changes a space's
--     member/admin edges (joinSpace, leaveSpace, addAdmin, removeAdmin, and
--     the synthetic space create).
-- Derived data: deleting it is safe — the next boot sweep rebuilds it.
create table if not exists space_stats (
  space_did     text primary key,
  member_count  integer not null,
  updated_at    integer not null default (unixepoch() * 1000)
) strict;
create index if not exists idx_space_stats_members on space_stats(member_count desc, space_did);

-- Voice: the calls the reconciler must verify against LiveKit, one row per
-- active call across every space. Maintained by the `callStarted`/`callEnded`
-- materialisers, which are the only writers — the reconciler reads this table
-- instead of opening every per-space DB on each 30 s pass.
--
-- Derived data: deleting it is safe, since the next `callStarted` replay (or
-- a per-space DB read) restores the row. Purely additive: this file is exec'd
-- on every open, so existing global DBs gain the table with no version bump.
create table if not exists voice_projected_calls (
  room_id    text primary key,
  space_id   text not null,
  call_id    text not null,
  started_at integer not null,
  created_at integer not null default (unixepoch() * 1000)
) strict;

create index if not exists idx_voice_projected_calls_space on voice_projected_calls(space_id);

-- Single-leader leases for the process-wide background loops. One row per
-- lease name; the holder is whoever last acquired it and has not yet passed
-- `expires_at`. A loop takes its lease before doing work, so N appserver
-- replicas produce one owner per loop rather than N.
create table if not exists worker_leases (
  name       text primary key,
  holder     text not null,
  expires_at integer not null,
  -- The fencing epoch: it advances when a different holder takes the lease, and
  -- a batch carrying an older epoch is refused. Loops here ignore it.
  epoch      integer not null default 1,
  updated_at integer not null default (unixepoch() * 1000)
) strict;

-- Consecutive LiveKit list failures, counted across replicas so a lease
-- handover does not reset the threshold. A successful pass deletes the row.
-- Three consecutive failures end every projected call: recovery over false
-- liveness, because a list that keeps failing says nothing about whether the
-- calls it would have listed are still alive.
create table if not exists voice_reconciler_failures (
  id              integer primary key check (id = 1),
  consecutive     integer not null,
  last_failure_at integer not null
) strict;

-- DNS space handles, one row per space that has one. The handle is assigned by
-- the space's PDS (or the domain's DNS) and changes without any on-protocol
-- write, so it is not derived from the event log and must not live in the
-- per-space DB — a space replayed from the log would silently lose it. Same
-- split as user profiles: authoritative here, and the per-space DB holds no
-- copy. Written by `space.roomy.space.setHandle`; read by `getMetadata` and
-- `getSpaces` (queries/spaceHandles.ts).
--
-- Purely additive: this file is exec'd on every open, so existing global DBs
-- gain the table with no version bump.
create table if not exists space_handles (
  space_did  text primary key,
  handle     text not null,
  updated_at integer not null default (unixepoch() * 1000)
) strict;
